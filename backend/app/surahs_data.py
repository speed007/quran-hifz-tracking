TOTAL_PAGES = 604


def build_surah_list():
    rows = []
    for i, (number, name_ar, name_en, start_page) in enumerate(SURAHS):
        end_page = (
            SURAHS[i + 1][3] - 1 if i + 1 < len(SURAHS) else TOTAL_PAGES
        )
        if end_page < start_page:
            end_page = start_page
        rows.append((number, name_ar, name_en, start_page, end_page))
    return rows
